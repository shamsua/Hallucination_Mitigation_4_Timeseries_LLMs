def load_ett(name: str) -> pd.DataFrame:
    df = pd.read_csv(ETT_URLS[name])
    df["date"] = pd.to_datetime(df["date"])
    return df.set_index("date").sort_index()


def find_ili_config() -> str:
    configs = get_dataset_config_names(ILI_HF_REPO)
    candidates = [c for c in configs if "ili" in c.lower() or "ill" in c.lower()]
    if not candidates:
        raise RuntimeError(f"No ILI/Illness config found in {ILI_HF_REPO}; configs={configs}")
    # Prefer the conventional ILI spelling if present.
    return next((c for c in candidates if c.lower() == "ili"), candidates[0])


def load_ili() -> pd.DataFrame:
    config = find_ili_config()
    ds = load_dataset(ILI_HF_REPO, name=config)
    split_name = "train" if "train" in ds else list(ds.keys())[0]
    df = ds[split_name].to_pandas()
    date_col = next(c for c in df.columns if c.lower() in {"date", "datetime", "date_time"})
    df[date_col] = pd.to_datetime(df[date_col])
    return df.set_index(date_col).sort_index()


def choose_target(df: pd.DataFrame, dataset_name: str) -> str:
    numeric = df.select_dtypes(include=[np.number]).columns.tolist()
    if dataset_name.startswith("ETT"):
        if "OT" not in df.columns:
            raise ValueError(f"ETT data has no OT column: {df.columns.tolist()}")
        return "OT"
    for col in ["ili", "ILI", "OT"]:
        if col in df.columns:
            return col
    if not numeric:
        raise ValueError(f"No numeric ILI target found: {df.columns.tolist()}")
    return numeric[-1]


def split_boundaries(dataset_name: str, n: int) -> Tuple[int, int, int]:
    if dataset_name.startswith("ETTh"):
        train = 12 * 30 * 24
        val = 4 * 30 * 24
        test = 4 * 30 * 24
    elif dataset_name.startswith("ETTm"):
        train = 12 * 30 * 24 * 4
        val = 4 * 30 * 24 * 4
        test = 4 * 30 * 24 * 4
    else:
        train = int(n * 0.7)
        val = int(n * 0.1)
        test = n - train - val
    expected = train + val + test
    if n < expected:
        raise ValueError(f"{dataset_name}: n={n}, expected at least {expected}")
    return train, train + val, min(expected, n)


def prepare_dataset(dataset_name: str):
    df = load_ili() if dataset_name == "ILI" else load_ett(dataset_name)
    target = choose_target(df, dataset_name)
    if dataset_name.startswith("ETTm"):
        freq = "15min"
    elif dataset_name.startswith("ETTh"):
        freq = "H"
    else:
        freq = pd.infer_freq(df.index) or "W"
    boundaries = split_boundaries(dataset_name, len(df))
    return df[[target]], target, freq, boundaries

"""# ## 4. Supplied metrics and leakage-safe calibration

"""

def mse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean((np.asarray(y_true) - np.asarray(y_pred)) ** 2))


def mae(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean(np.abs(np.asarray(y_true) - np.asarray(y_pred))))


def rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.sqrt(mse(y_true, y_pred)))


def mape(y_true: np.ndarray, y_pred: np.ndarray, epsilon: float = 1e-6) -> float:
    y_true, y_pred = np.asarray(y_true), np.asarray(y_pred)
    return float(100.0 * np.mean(np.abs(y_true - y_pred) / np.maximum(np.abs(y_true), epsilon)))


def temporal_consistency_error(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean(np.abs(np.diff(y_true, axis=1) - np.diff(y_pred, axis=1))))


def _dtw_1d(a: np.ndarray, b: np.ndarray) -> float:
    n, m = len(a), len(b)
    previous = np.full(m + 1, np.inf)
    previous[0] = 0.0
    for i in range(1, n + 1):
        current = np.full(m + 1, np.inf)
        for j in range(1, m + 1):
            current[j] = abs(a[i - 1] - b[j - 1]) + min(current[j - 1], previous[j], previous[j - 1])
        previous = current
    return float(previous[m] / max(n + m, 1))


def normalized_dtw(y_true: np.ndarray, y_pred: np.ndarray, max_samples: int = 256, seed: int = 0) -> float:
    rng = np.random.default_rng(seed)
    indices = np.arange(len(y_true))
    if len(indices) > max_samples:
        indices = np.sort(rng.choice(indices, max_samples, replace=False))
    return float(np.mean([_dtw_1d(y_true[i, :, c], y_pred[i, :, c]) for i in indices for c in range(y_true.shape[-1])]))


def calibrate_hr_thresholds(training_targets: np.ndarray, training_naive_predictions: np.ndarray, quantiles=(0.90, 0.95, 0.99)) -> Dict[float, np.ndarray]:
    errors = np.abs(np.asarray(training_targets) - np.asarray(training_naive_predictions))
    return {q: np.quantile(errors, q, axis=0) for q in quantiles}


def fit_gaussian_calibration(y_true: np.ndarray, y_pred: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    residual = np.asarray(y_true) - np.asarray(y_pred)
    return np.mean(residual, axis=0), np.maximum(np.std(residual, axis=0), 1e-6)


def gaussian_nll(y_true: np.ndarray, y_pred: np.ndarray, bias: np.ndarray, sigma: np.ndarray) -> float:
    residual = np.asarray(y_true) - np.asarray(y_pred) - bias
    variance = sigma ** 2
    return float(np.mean(0.5 * (np.log(2 * np.pi * variance) + residual ** 2 / variance)))


def evaluate_forecasts(y_true, y_pred, hr_thresholds, training_minimum, training_maximum, calibration=None) -> Dict[str, float]:
    result = {
        "mse": mse(y_true, y_pred),
        "mae": mae(y_true, y_pred),
        "rmse": rmse(y_true, y_pred),
        "mape": mape(y_true, y_pred),
        "tce": temporal_consistency_error(y_true, y_pred),
        "dtw": normalized_dtw(y_true, y_pred, DTW_MAX_SAMPLES, SEED),
        "range_violation_rate": float(np.mean((y_pred < training_minimum) | (y_pred > training_maximum))),
    }
    for q, thresholds in hr_thresholds.items():
        result[f"hr_q{int(round(q * 100)):02d}"] = float(np.mean(np.abs(y_true - y_pred) > thresholds))
    if calibration is not None:
        result["gaussian_nll"] = gaussian_nll(y_true, y_pred, *calibration)
    return result


def training_calibration(values: np.ndarray, train_end: int, horizon: int, max_windows: int = 4096):
    train_values = values[:train_end]
    ends = np.arange(max(horizon, 1), len(train_values) - horizon + 1)
    if len(ends) > max_windows:
        ends = np.linspace(ends[0], ends[-1], max_windows, dtype=int)
    targets = np.stack([train_values[e:e + horizon] for e in ends])
    naive = np.stack([np.repeat(train_values[e - 1][None, :], horizon, axis=0) for e in ends])
    return calibrate_hr_thresholds(targets, naive), train_values.min(axis=0)[None, None, :], train_values.max(axis=0)[None, None, :]

"""# ## 5. Official Lag-Llama checkpoint and rolling prediction

"""

def get_checkpoint() -> str:
    return hf_hub_download(repo_id=MODEL_REPO, filename=MODEL_FILENAME)


def build_predictor(horizon: int, checkpoint_path: str):
    estimator = LagLlamaEstimator(
        prediction_length=horizon,
        context_length=CONTEXT_LENGTH,
        input_size=1,
        n_layer=1,
        n_embd_per_head=32,
        n_head=4,
        max_context_length=MAX_CONTEXT_LENGTH,
        rope_scaling=None,
        scaling="mean",
        distr_output="studentT",
        num_parallel_samples=NUM_SAMPLES,
        batch_size=BATCH_SIZE,
        time_feat=False,
        ckpt_path=checkpoint_path,
        device=torch.device(DEVICE),
    )
    transformation = estimator.create_transformation()
    module = estimator.create_lightning_module()
    return estimator.create_predictor(transformation, module)


def predict_windows(df: pd.DataFrame, target: str, freq: str, cut: int, horizon: int, windows: int, checkpoint_path: str):
    ds = PandasDataset(df, target=target, freq=freq)
    _, template = split(ds, offset=cut)
    instances = template.generate_instances(prediction_length=horizon, windows=windows, distance=horizon)
    predictor = build_predictor(horizon, checkpoint_path)
    forecasts = predictor.predict(instances.input, num_samples=NUM_SAMPLES)
    y_true, y_pred = [], []
    for label, forecast in zip(instances.label, forecasts):
        truth = np.asarray(label["target"], dtype=np.float32)
        if truth.ndim == 1:
            truth = truth[:, None]
        samples = np.asarray(forecast.samples, dtype=np.float32)
        if samples.ndim == 1:
            samples = samples[None, :]
        pred = samples.mean(axis=0)[:, None]
        y_true.append(truth[-horizon:])
        y_pred.append(pred[-horizon:])
    del predictor, forecasts
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    gc.collect()
    return np.stack(y_true), np.stack(y_pred)

"""# ## 6. Resumable dataset runner
#
# Execute this section once per dataset. To continue after a disconnect, keep
# the same RESULTS_DIR and rerun; completed horizon checkpoints are skipped.

"""

def checkpoint_path(dataset_name: str, horizon: int) -> Path:
    return RESULTS_DIR / f"{dataset_name}_h{horizon}.json"


def run_dataset(dataset_name: str) -> pd.DataFrame:
    if dataset_name not in DATASETS:
        raise ValueError(f"dataset_name must be one of {DATASETS}")
    df, target, freq, (train_end, val_end, test_end) = prepare_dataset(dataset_name)
    values = df[[target]].to_numpy(dtype=np.float32)
    horizons = ILI_HORIZONS if dataset_name == "ILI" else ETT_HORIZONS
    checkpoint = get_checkpoint()
    all_rows = []
    partial_csv = RESULTS_DIR / f"{dataset_name}_partial_results.csv"

    for horizon in horizons:
        cp = checkpoint_path(dataset_name, horizon)
        if cp.exists():
            print(f"[skip] existing checkpoint: {cp.name}")
            all_rows.append(json.loads(cp.read_text()))
            continue

        print(f"\n=== {dataset_name} | horizon={horizon} ===")
        val_len, test_len = val_end - train_end, test_end - val_end
        val_windows, test_windows = val_len // horizon, test_len // horizon
        if val_windows < 1 or test_windows < 1:
            raise ValueError(f"Insufficient windows for {dataset_name}, h={horizon}: val={val_len}, test={test_len}")

        hr_thresholds, train_minimum, train_maximum = training_calibration(values, train_end, horizon)
        started = time.time()
        y_val, p_val = predict_windows(df, target, freq, train_end, horizon, val_windows, checkpoint)
        calibration = fit_gaussian_calibration(y_val, p_val)
        y_test, p_test = predict_windows(df, target, freq, val_end, horizon, test_windows, checkpoint)
        scores = evaluate_forecasts(y_test, p_test, hr_thresholds, train_minimum, train_maximum, calibration)
        row = {
            "dataset": dataset_name,
            "target": target,
            "freq": freq,
            "model": "Lag-Llama",
            "checkpoint_repo": MODEL_REPO,
            "horizon": horizon,
            "context_length": CONTEXT_LENGTH,
            "num_samples": NUM_SAMPLES,
            "validation_windows": val_windows,
            "test_windows": test_windows,
            "elapsed_seconds": round(time.time() - started, 2),
            **scores,
        }
        cp.write_text(json.dumps(row, indent=2))
        all_rows.append(row)
        pd.DataFrame(all_rows).sort_values("horizon").to_csv(partial_csv, index=False)
        print(json.dumps(row, indent=2))

    result = pd.DataFrame(all_rows).sort_values("horizon")
    result.to_csv(RESULTS_DIR / f"{dataset_name}_results.csv", index=False)
    aggregate_path = RESULTS_DIR / "all_results.csv"
    if aggregate_path.exists():
        old = pd.read_csv(aggregate_path)
        combined = pd.concat([old, result], ignore_index=True)
        combined = combined.drop_duplicates(subset=["dataset", "horizon"], keep="last")
    else:
        combined = result
    combined.sort_values(["dataset", "horizon"]).to_csv(aggregate_path, index=False)
    print(f"Saved {len(result)} rows to {RESULTS_DIR / f'{dataset_name}_results.csv'}")
    return result


if RUN_ALL_DATASETS:
    for _dataset in DATASETS:
        run_dataset(_dataset)
else:
    results = run_dataset(DATASET_TO_RUN)
    display(results)

