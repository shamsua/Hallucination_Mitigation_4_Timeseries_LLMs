import torch
import torch.nn as nn
import torch.nn.functional as F
from typing import Optional


# ── Building blocks ──────────────────────────────────────────────────────────

class GLU(nn.Module):
    def __init__(self, d_in: int, d_out: int):
        super().__init__()
        self.fc = nn.Linear(d_in, d_out * 2)

    def forward(self, x):
        x = self.fc(x)
        return F.glu(x, dim=-1)


class GRN(nn.Module):
    """Gated Residual Network."""
    def __init__(self, d_in: int, d_hidden: int, d_out: Optional[int] = None,
                 d_context: Optional[int] = None, dropout: float = 0.0):
        super().__init__()
        d_out = d_out or d_hidden
        self.fc_a  = nn.Linear(d_in, d_hidden)
        self.fc_c  = nn.Linear(d_context, d_hidden, bias=False) if d_context else None
        self.fc_i  = nn.Linear(d_hidden, d_hidden)
        self.glu   = GLU(d_hidden, d_out)
        self.ln    = nn.LayerNorm(d_out)
        self.skip  = nn.Linear(d_in, d_out) if d_in != d_out else nn.Identity()
        self.drop  = nn.Dropout(dropout)

    def forward(self, a, c: Optional[torch.Tensor] = None):
        x = self.fc_a(a)
        if c is not None and self.fc_c is not None:
            x = x + self.fc_c(c).unsqueeze(1) if c.dim() == 2 else x + self.fc_c(c)
        x = F.elu(x)
        x = self.fc_i(x)
        x = self.drop(x)
        x = self.glu(x)
        return self.ln(x + self.skip(a))


class VariableSelectionNetwork(nn.Module):
    """VSN assigns soft weights to input variables."""
    def __init__(self, n_vars: int, d_model: int, d_context: Optional[int] = None,
                 dropout: float = 0.0):
        super().__init__()
        self.d_model = d_model
        self.var_grns = nn.ModuleList([
            GRN(d_model, d_model, dropout=dropout) for _ in range(n_vars)
        ])
        self.softmax_grn = GRN(
            n_vars * d_model, d_model, d_out=n_vars,
            d_context=d_model, dropout=dropout
        )

    def forward(self, x_list: list[torch.Tensor],
                context: Optional[torch.Tensor] = None):
        # x_list: list of (B, T, d_model) or (B, d_model)
        processed = [grn(xv) for grn, xv in zip(self.var_grns, x_list)]
        stacked   = torch.stack(processed, dim=-2)          # (B, [T], n_vars, d)
        flat      = stacked.flatten(start_dim=-2)           # (B, [T], n_vars*d)
        weights   = F.softmax(
            self.softmax_grn(flat, context), dim=-1
        ).unsqueeze(-1)                                      # (B, [T], n_vars, 1)
        out = (stacked * weights).sum(dim=-2)               # (B, [T], d)
        return out, weights.squeeze(-1)


class InterpretableMultiHeadAttention(nn.Module):
    """Shared-value MHA from TFT paper (section 4.2)."""
    def __init__(self, d_model: int, n_heads: int, dropout: float = 0.0):
        super().__init__()
        assert d_model % n_heads == 0
        self.d_head  = d_model // n_heads
        self.n_heads = n_heads
        self.q_proj  = nn.Linear(d_model, d_model)
        self.k_proj  = nn.Linear(d_model, d_model)
        self.v_proj  = nn.Linear(d_model, self.d_head)  # shared V
        self.out_fc  = nn.Linear(self.d_head, d_model)
        self.drop    = nn.Dropout(dropout)

    def forward(self, q, k, v, mask: Optional[torch.Tensor] = None):
        B, T, _ = q.shape
        H, Dh   = self.n_heads, self.d_head

        Q = self.q_proj(q).view(B, T, H, Dh).transpose(1, 2)      # (B,H,T,Dh)
        K = self.k_proj(k).view(B, k.size(1), H, Dh).transpose(1, 2)
        V = self.v_proj(v)                                          # (B,T,Dh)  shared

        scale  = Dh ** -0.5
        scores = torch.matmul(Q, K.transpose(-2, -1)) * scale      # (B,H,T,T)
        if mask is not None:
            scores = scores.masked_fill(mask == 0, float('-inf'))
        attn   = self.drop(F.softmax(scores, dim=-1))

        # Expand shared V for all heads, then weighted sum
        V_exp  = V.unsqueeze(1).expand(-1, H, -1, -1)              # (B,H,T,Dh)
        out    = torch.matmul(attn, V_exp)                          # (B,H,T,Dh)
        out    = out.mean(dim=1)                                    # (B,T,Dh) mean over heads
        out    = self.out_fc(out)                                   # (B,T,d_model)
        return out, attn


# ── Full TFT model ───────────────────────────────────────────────────────────

class TemporalFusionTransformer(nn.Module):
    """
    TFT for continuous multivariate inputs → point + quantile forecasts.

    All input features are continuous (standard for ETT / Illness benchmarks).
    Architecture follows someonetookmynugget/Time-Series-Forecasting / NVIDIA TFT.
    """

    def __init__(
        self,
        n_features: int,        # number of input covariates
        d_model: int   = 64,
        n_heads: int   = 4,
        n_lstm_layers: int = 2,
        lookback: int  = 168,
        horizon: int   = 24,
        dropout: float = 0.1,
        n_quantiles: int = 3,   # [0.1, 0.5, 0.9]
    ):
        super().__init__()
        self.lookback    = lookback
        self.horizon     = horizon
        self.d_model     = d_model
        self.n_quantiles = n_quantiles
        self.quantiles   = [0.1, 0.5, 0.9]

        # ── Feature projection: each variable → d_model
        self.feat_proj = nn.ModuleList([
            nn.Linear(1, d_model) for _ in range(n_features)
        ])

        # ── Static context (mean-pooled from encoder input)
        self.static_ctx_grn = GRN(d_model, d_model, dropout=dropout)

        # ── Variable selection networks
        self.vsn_encoder = VariableSelectionNetwork(
            n_vars=n_features, d_model=d_model,
            d_context=d_model, dropout=dropout
        )
        self.vsn_decoder = VariableSelectionNetwork(
            n_vars=n_features, d_model=d_model,
            d_context=d_model, dropout=dropout
        )

        # ── LSTM encoder
        self.lstm_encoder = nn.LSTM(
            d_model, d_model, num_layers=n_lstm_layers,
            batch_first=True, dropout=dropout if n_lstm_layers > 1 else 0.0
        )
        # ── LSTM decoder
        self.lstm_decoder = nn.LSTM(
            d_model, d_model, num_layers=n_lstm_layers,
            batch_first=True, dropout=dropout if n_lstm_layers > 1 else 0.0
        )

        # ── Post-LSTM gating & layer norm
        self.glu_enc = GLU(d_model, d_model)
        self.glu_dec = GLU(d_model, d_model)
        self.ln_enc  = nn.LayerNorm(d_model)
        self.ln_dec  = nn.LayerNorm(d_model)

        # ── Enrichment GRN (static context → temporal features)
        self.enrich_grn = GRN(d_model, d_model, d_context=d_model, dropout=dropout)

        # ── Self-attention over decoder
        self.attn      = InterpretableMultiHeadAttention(d_model, n_heads, dropout)
        self.attn_ln   = nn.LayerNorm(d_model)
        self.attn_glu  = GLU(d_model, d_model)

        # ── Position-wise feedforward after attention
        self.ff_grn    = GRN(d_model, d_model, dropout=dropout)
        self.ff_ln     = nn.LayerNorm(d_model)

        # ── Quantile output projection
        self.out_proj  = nn.Linear(d_model, n_quantiles)

        self.drop = nn.Dropout(dropout)

    def _embed_features(self, x: torch.Tensor) -> list[torch.Tensor]:
        """(B, T, F) → list of F tensors each (B, T, d_model)."""
        return [proj(x[..., i:i+1]) for i, proj in enumerate(self.feat_proj)]

    def forward(self, x_enc: torch.Tensor, x_dec: torch.Tensor):
        """
        Parameters
        ----------
        x_enc : (B, lookback, n_features)
        x_dec : (B, dec_len, n_features)   where dec_len = horizon//2 + horizon

        Returns
        -------
        out : (B, horizon, n_quantiles)
        """
        B = x_enc.size(0)

        # ── 1. Feature embedding
        enc_embs = self._embed_features(x_enc)   # F × (B, lookback, d)
        dec_embs = self._embed_features(x_dec)   # F × (B, dec_len,  d)

        # ── 2. Static context = mean of encoder embeddings (simple proxy)
        ctx = torch.stack(enc_embs, dim=-2).mean(dim=-2).mean(dim=1)  # (B, d)
        ctx = self.static_ctx_grn(ctx)                                  # (B, d)

        # ── 3. Variable selection
        enc_vsn, _ = self.vsn_encoder(enc_embs, context=ctx.unsqueeze(1))  # (B, T, d)
        dec_vsn, _ = self.vsn_decoder(dec_embs, context=ctx.unsqueeze(1))  # (B, L, d)

        # ── 4. LSTM encoding
        enc_out, (h, c)  = self.lstm_encoder(enc_vsn)          # (B, T, d)
        dec_out, _       = self.lstm_decoder(dec_vsn, (h, c))  # (B, L, d)

        # ── 5. Post-LSTM gating
        enc_out = self.ln_enc(self.glu_enc(enc_out) + enc_vsn)
        dec_out = self.ln_dec(self.glu_dec(dec_out) + dec_vsn)

        # ── 6. Concatenate for attention (enc context + dec future)
        seq = torch.cat([enc_out, dec_out], dim=1)              # (B, T+L, d)

        # ── 7. Static enrichment
        ctx2d  = ctx.unsqueeze(1).expand(-1, seq.size(1), -1)  # (B, T+L, d)
        seq_e  = self.enrich_grn(seq, ctx2d)

        # ── 8. Causal self-attention (over full seq, extract decoder slice)
        total_len = seq_e.size(1)
        mask = torch.tril(torch.ones(total_len, total_len, device=x_enc.device)).unsqueeze(0)
        attn_out, _ = self.attn(seq_e, seq_e, seq_e, mask=mask)
        attn_out    = self.attn_ln(self.attn_glu(attn_out) + seq_e)

        # ── 9. Position-wise feedforward
        ff_out = self.ff_ln(self.ff_grn(attn_out) + attn_out)

        # ── 10. Extract future horizon slice (last `horizon` steps)
        future = ff_out[:, -self.horizon:, :]                   # (B, H, d)

        # ── 11. Quantile projection
        out = self.out_proj(future)                             # (B, H, 3)
        return out


