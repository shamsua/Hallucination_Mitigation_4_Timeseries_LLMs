"""## CELL 2 ─ Custom metrics module (exact code provided by user)"""

from __future__ import annotations
from dataclasses import dataclass
import numpy as np


def mse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean((np.asarray(y_true) - np.asarray(y_pred)) ** 2))


def mae(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.mean(np.abs(np.asarray(y_true) - np.asarray(y_pred))))


def rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    return float(np.sqrt(mse(y_true, y_pred)))


def mape(y_true: np.ndarray, y_pred: np.ndarray, epsilon: float = 1e-6) -> float:
    denominator = np.maximum(np.abs(y_true), epsilon)
    return float(100.0 * np.mean(np.abs(y_true - y_pred) / denominator))


def temporal_consistency_error(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """Difference of within-forecast transitions; time is axis 1."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    if y_true.ndim != 3:
        raise ValueError("Expected [samples, horizon, channels]")
    return float(np.mean(np.abs(np.diff(y_true, axis=1) - np.diff(y_pred, axis=1))))


def _dtw_1d(a: np.ndarray, b: np.ndarray) -> float:
    n, m = len(a), len(b)
    previous = np.full(m + 1, np.inf)
    previous[0] = 0.0
    for i in range(1, n + 1):
        current = np.full(m + 1, np.inf)
        for j in range(1, m + 1):
            current[j] = abs(a[i - 1] - b[j - 1]) + min(
                current[j - 1], previous[j], previous[j - 1]
            )
        previous = current
    return float(previous[m] / max(n + m, 1))


def normalized_dtw(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    max_samples: int = 128,     # keep Colab fast
    seed: int = 0,
) -> float:
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    rng = np.random.default_rng(seed)
    indices = np.arange(len(y_true))
    if len(indices) > max_samples:
        indices = np.sort(rng.choice(indices, max_samples, replace=False))
    distances = [
        _dtw_1d(y_true[i, :, c], y_pred[i, :, c])
        for i in indices
        for c in range(y_true.shape[-1])
    ]
    return float(np.mean(distances))


def calibrate_hr_thresholds(
    training_targets: np.ndarray,
    training_naive_predictions: np.ndarray,
    quantiles: tuple[float, ...] = (0.90, 0.95, 0.99),
) -> dict[float, np.ndarray]:
    errors = np.abs(np.asarray(training_targets) - np.asarray(training_naive_predictions))
    return {q: np.quantile(errors, q, axis=0) for q in quantiles}


def hallucination_rate(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    thresholds: np.ndarray,
) -> float:
    violations = np.abs(np.asarray(y_true) - np.asarray(y_pred)) > np.asarray(thresholds)
    return float(np.mean(violations))


def range_violation_rate(
    y_pred: np.ndarray,
    training_minimum: np.ndarray,
    training_maximum: np.ndarray,
) -> float:
    y_pred = np.asarray(y_pred)
    return float(np.mean((y_pred < training_minimum) | (y_pred > training_maximum)))


@dataclass
class GaussianCalibration:
    bias: np.ndarray
    sigma: np.ndarray


def fit_gaussian_calibration(y_true: np.ndarray, y_pred: np.ndarray) -> GaussianCalibration:
    residual = np.asarray(y_true) - np.asarray(y_pred)
    return GaussianCalibration(
        bias=np.mean(residual, axis=0),
        sigma=np.maximum(np.std(residual, axis=0), 1e-6),
    )


def gaussian_nll(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    calibration: GaussianCalibration,
) -> float:
    residual = np.asarray(y_true) - np.asarray(y_pred) - calibration.bias
    variance = calibration.sigma ** 2
    value = 0.5 * (np.log(2 * np.pi * variance) + residual ** 2 / variance)
    return float(np.mean(value))


def evaluate_forecasts(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    hr_thresholds: dict[float, np.ndarray],
    training_minimum: np.ndarray,
    training_maximum: np.ndarray,
    gaussian_calibration: GaussianCalibration | None = None,
    mape_epsilon: float = 1e-6,
    dtw_max_samples: int = 128,
    dtw_seed: int = 0,
) -> dict[str, float]:
    results = {
        "mse":                 mse(y_true, y_pred),
        "mae":                 mae(y_true, y_pred),
        "rmse":                rmse(y_true, y_pred),
        "mape":                mape(y_true, y_pred, mape_epsilon),
        "tce":                 temporal_consistency_error(y_true, y_pred),
        "dtw":                 normalized_dtw(y_true, y_pred, dtw_max_samples, dtw_seed),
        "range_violation_rate": range_violation_rate(
            y_pred, training_minimum, training_maximum),
    }
    for q, thresh in hr_thresholds.items():
        results[f"hr_q{int(round(q * 100)):02d}"] = hallucination_rate(y_true, y_pred, thresh)
    if gaussian_calibration is not None:
        results["gaussian_nll"] = gaussian_nll(y_true, y_pred, gaussian_calibration)
    return results


