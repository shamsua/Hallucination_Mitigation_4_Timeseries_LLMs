"""## CELL 6 ─ Quantile loss + training / inference routines"""

import torch.optim as optim
from tqdm.auto import tqdm

QUANTILES = [0.1, 0.5, 0.9]


def quantile_loss(pred: torch.Tensor, target: torch.Tensor,
                  quantiles: list = QUANTILES) -> torch.Tensor:
    """
    pred   : (B, H, Q)
    target : (B, H, 1)  – broadcast-compatible
    """
    losses = []
    for i, q in enumerate(quantiles):
        err = target - pred[:, :, i:i+1]
        losses.append(torch.max(q * err, (q - 1) * err))
    return torch.mean(torch.stack(losses, dim=-1))


def train_one_epoch(model, loader, optimiser, scaler_amp, device):
    model.train()
    total_loss = 0.0
    for x_enc, x_dec, y in loader:
        x_enc, x_dec, y = x_enc.to(device), x_dec.to(device), y.to(device)
        optimiser.zero_grad()
        with torch.amp.autocast("cuda", enabled=torch.cuda.is_available()):
            pred = model(x_enc, x_dec)           # (B, H, 3)
            loss = quantile_loss(pred, y)
        scaler_amp.scale(loss).backward()
        scaler_amp.unscale_(optimiser)
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        scaler_amp.step(optimiser)
        scaler_amp.update()
        total_loss += loss.item()
    return total_loss / max(len(loader), 1)


@torch.no_grad()
def evaluate(model, loader, device):
    model.eval()
    total_loss = 0.0
    for x_enc, x_dec, y in loader:
        x_enc, x_dec, y = x_enc.to(device), x_dec.to(device), y.to(device)
        pred = model(x_enc, x_dec)
        total_loss += quantile_loss(pred, y).item()
    return total_loss / max(len(loader), 1)


@torch.no_grad()
def collect_predictions(model, loader, device, scaler, target_idx):
    """
    Runs inference, inverse-transforms predictions and targets,
    returns arrays shaped (N, H, 1) ready for metric computation.
    """
    model.eval()
    all_pred, all_true = [], []
    n_feat    = scaler.mean_.shape[0]
    t_mean    = scaler.mean_[target_idx]      # (n_tgt,)
    t_std     = scaler.scale_[target_idx]     # (n_tgt,)

    for x_enc, x_dec, y in loader:
        x_enc = x_enc.to(device)
        x_dec = x_dec.to(device)
        pred  = model(x_enc, x_dec)           # (B, H, 3)
        # Use median quantile (index 1) as point forecast
        p_med = pred[:, :, 1:2].cpu().numpy()  # (B, H, 1)
        y_np  = y.numpy()                       # (B, H, 1)
        # Inverse normalise
        p_med = p_med * t_std + t_mean
        y_np  = y_np  * t_std + t_mean
        all_pred.append(p_med)
        all_true.append(y_np)

    return np.concatenate(all_pred, axis=0), np.concatenate(all_true, axis=0)


