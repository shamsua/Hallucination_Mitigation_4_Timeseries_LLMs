import torch
from torch.utils.data import Dataset, DataLoader
from sklearn.preprocessing import StandardScaler
import pandas as pd
import numpy as np

class TimeSeriesDataset(Dataset):
    """
    Sliding-window dataset for multivariate time-series forecasting.
    """
    def __init__(self, data: np.ndarray, lookback: int, horizon: int, target_idx: list):
        self.data       = data.astype(np.float32)
        self.lookback   = lookback
        self.horizon    = horizon
        self.target_idx = target_idx
        self.total      = len(data) - lookback - horizon + 1
        assert self.total > 0, (
            f"Not enough rows ({len(data)}) for lookback={lookback} + horizon={horizon}"
        )

    def __len__(self):
        return self.total

    def __getitem__(self, idx):
        s = idx
        e = idx + self.lookback
        x_enc = torch.tensor(self.data[s:e],                    dtype=torch.float32)
        x_dec = torch.tensor(self.data[e - self.horizon // 2: e + self.horizon], dtype=torch.float32)
        y     = torch.tensor(self.data[e: e + self.horizon, :][:, self.target_idx], dtype=torch.float32)
        return x_enc, x_dec, y


def load_dataset(
    csv_path: str,
    meta: dict,
    lookback: int,
    horizon: int,
    train_frac: float = 0.7,
    val_frac: float   = 0.1,
    batch_size: int   = 64,
):
    """
    Loads CSV, splits chronologically 70/10/20, fits StandardScaler on train,
    returns (train_loader, val_loader, test_loader, scaler, target_idx, raw_test_target).
    """
    df = pd.read_csv(csv_path)
    # Enable robust date parsing for mixed and dayfirst formats (like 13/11/2000)
    df[meta["date"]] = pd.to_datetime(df[meta["date"]], format="mixed", dayfirst=True)
    df = df.sort_values(meta["date"]).reset_index(drop=True)

    feature_cols = [c for c in df.columns if c != meta["date"]]
    if meta["target"] not in feature_cols:
        raise ValueError(f"Target column '{meta['target']}' not found. Columns: {feature_cols}")

    data_raw = df[feature_cols].values.astype(np.float32)
    T        = len(data_raw)
    n_train  = int(T * train_frac)
    n_val    = int(T * val_frac)

    train_raw = data_raw[:n_train]
    val_raw   = data_raw[n_train: n_train + n_val]
    test_raw  = data_raw[n_train + n_val:]

    scaler = StandardScaler()
    train_scaled = scaler.fit_transform(train_raw)
    val_scaled   = scaler.transform(val_raw)
    test_scaled  = scaler.transform(test_raw)

    target_idx = [feature_cols.index(meta["target"])]

    def _make_loader(arr, shuffle):
        if len(arr) < lookback + horizon:
            return None
        ds = TimeSeriesDataset(arr, lookback, horizon, target_idx)
        if len(ds) == 0:
            return None
        return DataLoader(ds, batch_size=batch_size, shuffle=shuffle,
                          num_workers=0, pin_memory=torch.cuda.is_available())

    train_loader = _make_loader(train_scaled, shuffle=True)
    val_loader   = _make_loader(val_scaled,   shuffle=False)
    test_loader  = _make_loader(test_scaled,  shuffle=False)

    raw_test = test_raw[:, target_idx]

    return train_loader, val_loader, test_loader, scaler, target_idx, raw_test, feature_cols

