# 7. HALLUCINATION RATE
# ============================================================

def hallucination_rate(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    thresholds: np.ndarray,
) -> float:
    """
    Hallucination Rate (HR).

    HR is the proportion of forecast values whose absolute
    error exceeds the calibrated training threshold.

    Returns:
        proportion in [0, 1]
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    thresholds = np.asarray(thresholds)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes."
        )

    if thresholds.shape != y_true.shape[1:]:
        raise ValueError(
            "Threshold shape must be "
            "[horizon, channels]. "
            f"Received threshold shape "
            f"{thresholds.shape}, while forecast shape is "
            f"{y_true.shape}"
        )

    violations = (
        np.abs(y_true - y_pred)
        > thresholds
    )

    return float(
        np.mean(violations)
    )


