def mse(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> float:
    """
    Mean Squared Error.

    Expected shape:
        [samples, horizon, channels]
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    return float(
        np.mean((y_true - y_pred) ** 2)
    )


def mae(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> float:
    """
    Mean Absolute Error.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    return float(
        np.mean(np.abs(y_true - y_pred))
    )


def rmse(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> float:
    """
    Root Mean Squared Error.
    """
    return float(
        np.sqrt(mse(y_true, y_pred))
    )


def mape(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    epsilon: float = 1e-6,
) -> float:
    """
    Mean Absolute Percentage Error.

    Returns percentage.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    denominator = np.maximum(
        np.abs(y_true),
        epsilon
    )

    return float(
        100.0
        * np.mean(
            np.abs(y_true - y_pred) / denominator
        )
    )


