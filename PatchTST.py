# 8. RANGE VIOLATION RATE
# ============================================================

def range_violation_rate(
    y_pred: np.ndarray,
    training_minimum: np.ndarray,
    training_maximum: np.ndarray,
) -> float:
    """
    Range Violation Rate (RVR).

    Measures the fraction of predictions falling outside
    the observed training range.

    training_minimum shape:
        [channels]

    training_maximum shape:
        [channels]
    """

    y_pred = np.asarray(y_pred)

    training_minimum = np.asarray(
        training_minimum
    )

    training_maximum = np.asarray(
        training_maximum
    )

    violations = (
        (y_pred < training_minimum)
        |
        (y_pred > training_maximum)
    )

    return float(
        np.mean(violations)
    )


