def calibrate_hr_thresholds(
    training_targets: np.ndarray,
    training_naive_predictions: np.ndarray,
    quantiles: tuple[float, ...] = (
        0.90,
        0.95,
        0.99,
    ),
) -> dict[float, np.ndarray]:
    """
    Calibrate hallucination thresholds using TRAINING
    windows only.

    The threshold is calculated horizon-wise and
    channel-wise.

    Expected shape:
        [samples, horizon, channels]

    Returns:
        {
            0.90: [horizon, channels],
            0.95: [horizon, channels],
            0.99: [horizon, channels]
        }
    """

    training_targets = np.asarray(
        training_targets
    )

    training_naive_predictions = np.asarray(
        training_naive_predictions
    )

    if training_targets.shape != training_naive_predictions.shape:
        raise ValueError(
            "Training targets and naive predictions "
            "must have identical shapes. "
            f"Received "
            f"{training_targets.shape} and "
            f"{training_naive_predictions.shape}"
        )

    errors = np.abs(
        training_targets
        - training_naive_predictions
    )

    return {
        q: np.quantile(
            errors,
            q,
            axis=0,
        )
        for q in quantiles
    }


