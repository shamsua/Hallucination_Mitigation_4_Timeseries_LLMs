# 16. RUN EXPERIMENT
# ============================================================

def run_experiment(
    dataset_name,
    use_hsqp=False,
):

    print("\n" + "=" * 75)
    print(
        f"RUNNING DATASET: {dataset_name}"
    )
    print("=" * 75)

    filename = DATASET_MAPPING.get(
        dataset_name
    )

    if filename is None:
        print(
            f"Dataset '{dataset_name}' "
            f"is not defined in DATASET_MAPPING."
        )
        return None

    path = os.path.join(
        "PatchTST",
        "data",
        filename,
    )

    if not os.path.exists(path):
        print(
            f"Dataset file not found:\n{path}"
        )
        return None

    # --------------------------------------------------------
    # Load data
    # --------------------------------------------------------

    df = pd.read_csv(path)

    if df.shape[1] < 2:
        raise ValueError(
            f"{dataset_name}: expected at least "
            f"one time/index column and one feature column."
        )

    # First column assumed to be timestamp/index
    raw_data = (
        df.iloc[:, 1:]
        .values
        .astype(np.float32)
    )

    n_vars = raw_data.shape[1]

    print(
        f"Number of variables: {n_vars}"
    )

    # --------------------------------------------------------
    # Train/test split BEFORE scaling
    # --------------------------------------------------------

    train_size = int(
        len(raw_data) * 0.8
    )

    train_raw = raw_data[
        :train_size
    ]

    test_raw = raw_data[
        train_size:
    ]

    print(
        f"Total data length : {len(raw_data)}"
    )

    print(
        f"Train data length : {len(train_raw)}"
    )

    print(
        f"Test data length  : {len(test_raw)}"
    )

    required_length = (
        HP_CONFIG["seq_len"]
        + HP_CONFIG["pred_len"]
        - 1
    )

    if (
        len(train_raw)
        < required_length
        or
        len(test_raw)
        < required_length
    ):

        print(
            "\nSkipping experiment because "
            "there are not enough observations."
        )

        return None

    # --------------------------------------------------------
    # Scale using TRAINING data ONLY
    # --------------------------------------------------------

    scaler = StandardScaler()

    train_scaled = scaler.fit_transform(
        train_raw
    ).astype(np.float32)

    test_scaled = scaler.transform(
        test_raw
    ).astype(np.float32)

    # --------------------------------------------------------
    # Data loaders
    # --------------------------------------------------------

    train_dataset = TimeSeriesDataset(
        train_scaled,
        HP_CONFIG["seq_len"],
        HP_CONFIG["pred_len"],
    )

    test_dataset = TimeSeriesDataset(
        test_scaled,
        HP_CONFIG["seq_len"],
        HP_CONFIG["pred_len"],
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=HP_CONFIG["batch_size"],
        shuffle=True,
        pin_memory=torch.cuda.is_available(),
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=HP_CONFIG["batch_size"],
        shuffle=False,
        pin_memory=torch.cuda.is_available(),
    )

    print(
        f"Training samples: {len(train_dataset)}"
    )

    print(
        f"Testing samples : {len(test_dataset)}"
    )

    # --------------------------------------------------------
    # Device
    # --------------------------------------------------------

    device = torch.device(
        "cuda"
        if torch.cuda.is_available()
        else "cpu"
    )

    print(
        f"Device: {device}"
    )

    if torch.cuda.is_available():
        print(
            f"GPU: "
            f"{torch.cuda.get_device_name(0)}"
        )

    # --------------------------------------------------------
    # Model
    # --------------------------------------------------------

    model = PatchTST_backbone(
        c_in=n_vars,
        context_window=HP_CONFIG["seq_len"],
        target_window=HP_CONFIG["pred_len"],
        patch_len=HP_CONFIG["patch_len"],
        stride=HP_CONFIG["stride"],
        n_layers=HP_CONFIG["n_layers"],
        d_model=HP_CONFIG["d_model"],
        n_heads=HP_CONFIG["n_heads"],
        use_hsqp=use_hsqp,
    ).to(device)

    optimizer = Adam(
        model.parameters(),
        lr=HP_CONFIG["learning_rate"],
    )

    criterion = nn.MSELoss()

    # --------------------------------------------------------
    # Training
    # --------------------------------------------------------

    print("\nTraining...")

    model.train()

    for epoch in range(
        HP_CONFIG["epochs"]
    ):

        epoch_loss = 0.0

        for x, y in train_loader:

            x = x.to(
                device,
                non_blocking=True
            )

            y = y.to(
                device,
                non_blocking=True
            )

            optimizer.zero_grad(
                set_to_none=True
            )

            output = model(x)

            # Safety check
            if output.shape != y.shape:
                raise RuntimeError(
                    "Model output shape does not "
                    "match target shape.\n"
                    f"Output: {output.shape}\n"
                    f"Target: {y.shape}"
                )

            loss = criterion(
                output,
                y
            )

            loss.backward()

            optimizer.step()

            epoch_loss += (
                loss.item()
                * x.size(0)
            )

        epoch_loss /= max(
            len(train_dataset),
            1,
        )

        print(
            f"Epoch "
            f"{epoch + 1:02d}/"
            f"{HP_CONFIG['epochs']:02d} | "
            f"Loss: {epoch_loss:.6f}"
        )

    # --------------------------------------------------------
    # Generate TEST predictions
    # --------------------------------------------------------

    print("\nGenerating predictions...")

    model.eval()

    preds = []
    trues = []

    with torch.no_grad():

        for x, y in test_loader:

            x = x.to(
                device,
                non_blocking=True
            )

            output = model(x)

            preds.append(
                output.cpu().numpy()
            )

            trues.append(
                y.numpy()
            )

    if not preds:

        print(
            "No predictions generated."
        )

        return None

    preds_scaled = np.concatenate(
        preds,
        axis=0
    )

    trues_scaled = np.concatenate(
        trues,
        axis=0
    )

    # --------------------------------------------------------
    # CRITICAL SHAPE FIX
    # --------------------------------------------------------
    #
    # PatchTST:
    #     [N, V, H]
    #
    # Metrics:
    #     [N, H, V]
    #
    # Therefore transpose axes 1 and 2.
    # --------------------------------------------------------

    preds_scaled = np.transpose(
        preds_scaled,
        (0, 2, 1)
    )

    trues_scaled = np.transpose(
        trues_scaled,
        (0, 2, 1)
    )

    print(
        "\nPrediction shape after "
        f"conversion: {preds_scaled.shape}"
    )

    print(
        f"Target shape after conversion: "
        f"{trues_scaled.shape}"
    )

    expected_shape = (
        len(test_dataset),
        HP_CONFIG["pred_len"],
        n_vars,
    )

    if preds_scaled.shape != expected_shape:
        raise RuntimeError(
            "Unexpected prediction shape.\n"
            f"Expected: {expected_shape}\n"
            f"Received: {preds_scaled.shape}"
        )

    # --------------------------------------------------------
    # Inverse transform to ORIGINAL units
    # --------------------------------------------------------

    # StandardScaler inverse transform expects:
    # [samples, variables]
    #
    # Flatten forecast horizon first.

    n_test = preds_scaled.shape[0]
    horizon = preds_scaled.shape[1]

    preds_original = scaler.inverse_transform(
        preds_scaled.reshape(
            -1,
            n_vars
        )
    ).reshape(
        n_test,
        horizon,
        n_vars,
    )

    trues_original = scaler.inverse_transform(
        trues_scaled.reshape(
            -1,
            n_vars
        )
    ).reshape(
        n_test,
        horizon,
        n_vars,
    )

    # --------------------------------------------------------
    # BUILD TRAINING WINDOWS FOR CALIBRATION
    # --------------------------------------------------------

    train_inputs_original, train_targets_original = (
        create_forecasting_windows(
            train_raw,
            HP_CONFIG["seq_len"],
            HP_CONFIG["pred_len"],
        )
    )

    # --------------------------------------------------------
    # TRAINING NAIVE PREDICTIONS
    # --------------------------------------------------------

    train_naive_predictions = (
        create_persistence_predictions(
            train_inputs_original,
            HP_CONFIG["pred_len"],
        )
    )

    print(
        "\nCalibration data:"
    )

    print(
        f"Training targets: "
        f"{train_targets_original.shape}"
    )

    print(
        f"Training naive predictions: "
        f"{train_naive_predictions.shape}"
    )

    # --------------------------------------------------------
    # HR THRESHOLD CALIBRATION
    # --------------------------------------------------------

    hr_thresholds = calibrate_hr_thresholds(
        training_targets=train_targets_original,
        training_naive_predictions=train_naive_predictions,
        quantiles=HR_QUANTILES,
    )

    print(
        "\nHR thresholds calibrated at:"
    )

    for q, threshold in hr_thresholds.items():

        print(
            f"  q={q:.2f}: "
            f"shape={threshold.shape}"
        )

    # --------------------------------------------------------
    # TRAINING RANGE
    # --------------------------------------------------------

    training_minimum = np.min(
        train_raw,
        axis=0,
    )

    training_maximum = np.max(
        train_raw,
        axis=0,
    )

    # --------------------------------------------------------
    # GAUSSIAN CALIBRATION
    # --------------------------------------------------------

    gaussian_calibration = (
        fit_gaussian_calibration(
            train_targets_original,
            train_naive_predictions,
        )
    )

    print(
        "\nGaussian calibration:"
    )

    print(
        f"  Bias shape : "
        f"{gaussian_calibration.bias.shape}"
    )

    print(
        f"  Sigma shape: "
        f"{gaussian_calibration.sigma.shape}"
    )

    # --------------------------------------------------------
    # FINAL TEST METRICS
    # --------------------------------------------------------

    results = evaluate_forecasts(
        y_true=trues_original,
        y_pred=preds_original,
        hr_thresholds=hr_thresholds,
        training_minimum=training_minimum,
        training_maximum=training_maximum,
        gaussian_calibration=gaussian_calibration,
        mape_epsilon=MAPE_EPSILON,
        dtw_max_samples=DTW_MAX_SAMPLES,
        dtw_seed=DTW_SEED,
    )

    # --------------------------------------------------------
    # DISPLAY RESULTS
    # --------------------------------------------------------

    display_results = {
        "MSE": results["mse"],
        "MAE": results["mae"],
        "RMSE": results["rmse"],
        "MAPE (%)": results["mape"],
        "TCE": results["tce"],
        "Normalized DTW": results["dtw"],
        "HR q=0.90 (%)":
            results["hr_q90"] * 100.0,
        "HR q=0.95 (%)":
            results["hr_q95"] * 100.0,
        "HR q=0.99 (%)":
            results["hr_q99"] * 100.0,
        "Range Violation Rate (%)":
            results["range_violation_rate"] * 100.0,
        "Gaussian NLL":
            results["gaussian_nll"],
        "Gaussian Perplexity":
            results["gaussian_perplexity"],
    }

    print("\n" + "=" * 75)
    print(
        f"FINAL RESULTS: {dataset_name}"
    )
    print("=" * 75)

    result_table = pd.DataFrame(
        [
            {
                "Metric": key,
                "Value": value,
            }
            for key, value
            in display_results.items()
        ]
    )

    print(
        tabulate(
            result_table,
            headers="keys",
            tablefmt="github",
            showindex=False,
            floatfmt=".6f",
        )
    )

    # --------------------------------------------------------
    # RETURN COMPLETE RESULT PACKAGE
    # --------------------------------------------------------

    return {
        "dataset": dataset_name,
        "use_hsqp": use_hsqp,

        # Metrics
        "metrics": results,

        # Human-readable metrics
        "display_metrics": display_results,

        # Predictions
        "y_true": trues_original,
        "y_pred": preds_original,

        # Calibration
        "hr_thresholds": hr_thresholds,
        "gaussian_calibration":
            gaussian_calibration,

        # Training range
        "training_minimum":
            training_minimum,
        "training_maximum":
            training_maximum,

        # Model
        "model": model,

        # Scaler
        "scaler": scaler,
    }


