# ============================================================

@dataclass
class GaussianCalibration:
    bias: np.ndarray
    sigma: np.ndarray


def fit_gaussian_calibration(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> GaussianCalibration:
    """
    Fit Gaussian residual calibration using TRAINING data.

    bias and sigma are estimated horizon-wise and
    channel-wise.
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes."
        )

    residual = (
        y_true - y_pred
    )

    bias = np.mean(
        residual,
        axis=0
    )

    sigma = np.maximum(
        np.std(
            residual,
            axis=0
        ),
        1e-6
    )

    return GaussianCalibration(
        bias=bias,
        sigma=sigma,
    )


# ============================================================
# 10. GAUSSIAN NLL
# ============================================================

def gaussian_nll(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    calibration: GaussianCalibration,
) -> float:
    """
    Gaussian Negative Log-Likelihood.

    Calibration parameters are expected to have shape:

        [horizon, channels]
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    residual = (
        y_true
        - y_pred
        - calibration.bias
    )

    variance = (
        calibration.sigma ** 2
    )

    value = 0.5 * (
        np.log(
            2.0
            * np.pi
            * variance
        )
        +
        residual ** 2
        / variance
    )

    return float(
        np.mean(value)
    )


# ============================================================
# 11. GAUSSIAN PERPLEXITY
# ============================================================

def gaussian_perplexity(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    calibration: GaussianCalibration,
) -> float:
    """
    Continuous Gaussian likelihood perplexity.

    IMPORTANT:
    This is NOT token-level language-model perplexity.

    It is exp(mean Gaussian NLL).
    """

    mean_nll = gaussian_nll(
        y_true,
        y_pred,
        calibration,
    )

    return float(
        np.exp(
            np.clip(
                mean_nll,
                -700.0,
                700.0,
            )
        )
    )


