class TimeSeriesDataset(Dataset):

    def __init__(
        self,
        data,
        seq_len,
        pred_len,
    ):

        self.seq_len = seq_len
        self.pred_len = pred_len
        self.data = data

    def __len__(self):

        return max(
            0,
            len(self.data)
            - self.seq_len
            - self.pred_len
            + 1,
        )

    def __getitem__(self, idx):

        x = self.data[
            idx:
            idx + self.seq_len
        ]

        y = self.data[
            idx + self.seq_len:
            idx + self.seq_len + self.pred_len
        ]

        # Original PatchTST format:
        # [variables, time]
        return (
            torch.from_numpy(x)
            .float()
            .permute(1, 0),

            torch.from_numpy(y)
            .float()
            .permute(1, 0),
        )


# ============================================================
# 14. CREATE WINDOWS FOR METRIC CALIBRATION
# ============================================================

def create_forecasting_windows(
    data: np.ndarray,
    seq_len: int,
    pred_len: int,
):
    """
    Creates forecasting windows in numpy.

    Returns:

        inputs:
            [samples, seq_len, channels]

        targets:
            [samples, pred_len, channels]
    """

    data = np.asarray(data)

    n_samples = (
        len(data)
        - seq_len
        - pred_len
        + 1
    )

    if n_samples <= 0:
        raise ValueError(
            "Insufficient data for window creation. "
            f"Data length={len(data)}, "
            f"seq_len={seq_len}, "
            f"pred_len={pred_len}."
        )

    inputs = np.stack(
        [
            data[
                i:
                i + seq_len
            ]
            for i in range(n_samples)
        ],
        axis=0,
    )

    targets = np.stack(
        [
            data[
                i + seq_len:
                i + seq_len + pred_len
            ]
            for i in range(n_samples)
        ],
        axis=0,
    )

    return inputs, targets


# ============================================================
# 15. CREATE NAIVE BASELINE
# ============================================================

def create_persistence_predictions(
    inputs: np.ndarray,
    pred_len: int,
):
    """
    Persistence / naive forecast.

    The last observed value is repeated throughout
    the forecasting horizon.

    Input:
        [samples, seq_len, channels]

    Output:
        [samples, pred_len, channels]
    """

    last_value = inputs[:, -1:, :]

    return np.repeat(
        last_value,
        pred_len,
        axis=1,
    )


