# 5. NORMALIZED DTW
# ============================================================

def _dtw_1d(
    a: np.ndarray,
    b: np.ndarray,
) -> float:
    """
    Classical 1D Dynamic Time Warping.

    Normalized by n + m.
    """
    a = np.asarray(a)
    b = np.asarray(b)

    n = len(a)
    m = len(b)

    previous = np.full(
        m + 1,
        np.inf,
        dtype=np.float64
    )

    previous[0] = 0.0

    for i in range(1, n + 1):

        current = np.full(
            m + 1,
            np.inf,
            dtype=np.float64
        )

        for j in range(1, m + 1):

            current[j] = (
                abs(a[i - 1] - b[j - 1])
                + min(
                    current[j - 1],
                    previous[j],
                    previous[j - 1],
                )
            )

        previous = current

    return float(
        previous[m] / max(n + m, 1)
    )


def normalized_dtw(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    max_samples: int = 256,
    seed: int = 0,
) -> float:
    """
    Normalized DTW averaged across sampled forecasts
    and all channels.

    Expected shape:
        [samples, horizon, channels]
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.ndim != 3:
        raise ValueError(
            "Expected y_true with shape "
            "[samples, horizon, channels]. "
            f"Received {y_true.shape}"
        )

    if y_pred.shape != y_true.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes. "
            f"Received {y_true.shape} and {y_pred.shape}"
        )

    rng = np.random.default_rng(seed)

    indices = np.arange(len(y_true))

    if len(indices) > max_samples:
        indices = np.sort(
            rng.choice(
                indices,
                max_samples,
                replace=False
            )
        )

    distances = []

    for i in indices:

        for channel in range(y_true.shape[-1]):

            distance = _dtw_1d(
                y_true[i, :, channel],
                y_pred[i, :, channel],
            )

            distances.append(distance)

    if not distances:
        return float("nan")

    return float(
        np.mean(distances)
    )


