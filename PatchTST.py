def temporal_consistency_error(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> float:
    """
    Temporal Consistency Error (TCE).

    Measures the difference between the temporal transitions
    of the true and predicted forecasts.

    Expected shape:
        [samples, horizon, channels]

    Time axis = 1.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.ndim != 3:
        raise ValueError(
            "Expected y_true with shape "
            "[samples, horizon, channels]. "
            f"Received shape: {y_true.shape}"
        )

    if y_pred.shape != y_true.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes. "
            f"Received {y_true.shape} and {y_pred.shape}"
        )

    true_diff = np.diff(y_true, axis=1)
    pred_diff = np.diff(y_pred, axis=1)

    return float(
        np.mean(
            np.abs(true_diff - pred_diff)
        )
    )


