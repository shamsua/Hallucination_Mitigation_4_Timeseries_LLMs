def load_dataset(
    name,
    seq_len=96,
    pred_len=96,
    train_ratio=0.7,
    val_ratio=0.1,
    window_step=None,
):
    """
    Load dataset and prepare test windows plus
    training-based calibration information.

    Returns
    -------
    context_windows :
        list/array of test context windows

    gt_array :
        test ground truth
        [n_windows, pred_len, 1]

    scaler :
        StandardScaler fitted ONLY on training data

    calibration :
        dictionary containing:
            hr_thresholds
            training_minimum
            training_maximum
            gaussian_calibration_data
    """

    # --------------------------------------------------------
    # Configuration
    # --------------------------------------------------------

    if name not in DATASET_CONFIGS:

        raise ValueError(
            f"Unknown dataset '{name}'. "
            f"Available datasets: "
            f"{list(DATASET_CONFIGS.keys())}"
        )

    (
        fname,
        date_col,
        target_col,
        dayfirst,
    ) = DATASET_CONFIGS[name]

    path = f"dataset/{fname}"

    if not os.path.exists(path):

        raise FileNotFoundError(
            f"{path} not found. "
            "Upload it to dataset/ first."
        )

    # --------------------------------------------------------
    # Load CSV
    # --------------------------------------------------------

    df = pd.read_csv(path)

    # --------------------------------------------------------
    # Date processing
    # --------------------------------------------------------

    if date_col in df.columns:

        df[date_col] = pd.to_datetime(
            df[date_col],
            dayfirst=dayfirst,
            errors="coerce",
        )

        df = (
            df.dropna(
                subset=[date_col]
            )
            .sort_values(date_col)
            .reset_index(drop=True)
        )

    # --------------------------------------------------------
    # Target column
    # --------------------------------------------------------

    if target_col not in df.columns:

        numeric_cols = (
            df.select_dtypes(
                include=np.number
            )
            .columns
            .tolist()
        )

        if not numeric_cols:

            raise ValueError(
                f"No numeric columns found in {path}."
            )

        target_col = numeric_cols[0]

        print(
            f"  WARN: '{DATASET_CONFIGS[name][2]}' "
            f"not found; using '{target_col}'."
        )

    # --------------------------------------------------------
    # Extract target
    # --------------------------------------------------------

    series = df[
        target_col
    ].astype(float).values

    # --------------------------------------------------------
    # Handle missing values
    # --------------------------------------------------------

    if np.isnan(series).any():

        missing_count = np.isnan(
            series
        ).sum()

        print(
            f"  WARN: {missing_count} missing "
            "values detected; interpolating."
        )

        series = (
            pd.Series(series)
            .interpolate(
                method="linear"
            )
            .bfill()
            .ffill()
            .values
        )

    # --------------------------------------------------------
    # Chronological split
    # --------------------------------------------------------

    n = len(series)

    train_end = int(
        n * train_ratio
    )

    val_end = int(
        n * (
            train_ratio
            + val_ratio
        )
    )

    train_series = series[
        :train_end
    ]

    val_series = series[
        train_end:val_end
    ]

    test_series = series[
        val_end:
    ]

    # --------------------------------------------------------
    # Fit scaler ONLY on training data
    # --------------------------------------------------------

    scaler = StandardScaler()

    scaler.fit(
        train_series.reshape(-1, 1)
    )

    train_scaled = (
        scaler.transform(
            train_series.reshape(-1, 1)
        )
        .flatten()
    )

    val_scaled = (
        scaler.transform(
            val_series.reshape(-1, 1)
        )
        .flatten()
    )

    test_scaled = (
        scaler.transform(
            test_series.reshape(-1, 1)
        )
        .flatten()
    )

    # --------------------------------------------------------
    # Window stride
    # --------------------------------------------------------

    if window_step is None:

        # Preserve your original behaviour:
        # non-overlapping windows.
        window_step = pred_len

    # --------------------------------------------------------
    # TEST WINDOWS
    # --------------------------------------------------------

    test_context_windows, test_gt_windows = (
        create_windows(
            test_scaled,
            seq_len=seq_len,
            pred_len=pred_len,
            step=window_step,
        )
    )

    # --------------------------------------------------------
    # TRAINING WINDOWS
    # --------------------------------------------------------

    train_context_windows, train_gt_windows = (
        create_windows(
            train_scaled,
            seq_len=seq_len,
            pred_len=pred_len,
            step=window_step,
        )
    )

    # --------------------------------------------------------
    # VALIDATION WINDOWS
    # --------------------------------------------------------

    val_context_windows, val_gt_windows = (
        create_windows(
            val_scaled,
            seq_len=seq_len,
            pred_len=pred_len,
            step=window_step,
        )
    )

    # --------------------------------------------------------
    # NAIVE TRAINING FORECAST
    # --------------------------------------------------------

    train_naive_predictions = (
        persistence_forecast(
            train_context_windows,
            pred_len,
        )
    )

    # --------------------------------------------------------
    # HR CALIBRATION
    # --------------------------------------------------------

    hr_thresholds = (
        calibrate_hr_thresholds(
            training_targets=train_gt_windows,
            training_naive_predictions=
                train_naive_predictions,
            quantiles=(
                0.90,
                0.95,
                0.99,
            ),
        )
    )

    # --------------------------------------------------------
    # TRAINING RANGE
    # --------------------------------------------------------

    training_minimum = np.min(
        train_scaled
    )

    training_maximum = np.max(
        train_scaled
    )

    # --------------------------------------------------------
    # GAUSSIAN CALIBRATION DATA
    # --------------------------------------------------------
    #
    # We return validation targets and a naive validation
    # prediction so Gaussian calibration can be fitted
    # separately without using the TEST set.
    #
    # This is intentionally not fitted here to avoid
    # coupling the loader to the metrics module.
    # --------------------------------------------------------

    val_naive_predictions = (
        persistence_forecast(
            val_context_windows,
            pred_len,
        )
    )

    # --------------------------------------------------------
    # PRINT SUMMARY
    # --------------------------------------------------------

    print(
        f"\n  {name}"
    )

    print(
        f"  Total observations : {n:,}"
    )

    print(
        f"  Train observations : "
        f"{len(train_series):,}"
    )

    print(
        f"  Validation         : "
        f"{len(val_series):,}"
    )

    print(
        f"  Test observations  : "
        f"{len(test_series):,}"
    )

    print(
        f"  Train windows      : "
        f"{len(train_context_windows):,}"
    )

    print(
        f"  Validation windows : "
        f"{len(val_context_windows):,}"
    )

    print(
        f"  Test windows       : "
        f"{len(test_context_windows):,}"
    )

    print(
        f"  Window             : "
        f"seq={seq_len}, pred={pred_len}, "
        f"step={window_step}"
    )

    print(
        f"  Training range     : "
        f"[{training_minimum:.4f}, "
        f"{training_maximum:.4f}]"
    )

    print(
        "  HR thresholds      : "
        "q90, q95, q99"
    )

    # --------------------------------------------------------
    # RETURN
    # --------------------------------------------------------

    calibration = {

        "hr_thresholds":
            hr_thresholds,

        "training_minimum":
            np.array(
                training_minimum,
                dtype=np.float32,
            ),

        "training_maximum":
            np.array(
                training_maximum,
                dtype=np.float32,
            ),

        "train_targets":
            train_gt_windows,

        "train_naive_predictions":
            train_naive_predictions,

        "val_targets":
            val_gt_windows,

        "val_naive_predictions":
            val_naive_predictions,
    }

    return (
        test_context_windows,
        test_gt_windows,
        scaler,
        calibration,
    )


