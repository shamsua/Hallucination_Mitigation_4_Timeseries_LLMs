# CREATE FORECAST WINDOWS
# ============================================================

def create_windows(
    series,
    seq_len,
    pred_len,
    step,
):
    """
    Create context and forecasting windows.

    Parameters
    ----------
    series : 1-D array
        Time-series values.

    seq_len : int
        Historical context length.

    pred_len : int
        Forecast horizon.

    step : int
        Window stride.

    Returns
    -------
    context_windows :
        [n_windows, seq_len]

    gt_windows :
        [n_windows, pred_len, 1]
    """

    series = np.asarray(
        series,
        dtype=float,
    )

    context_windows = []
    gt_windows = []

    max_start = (
        len(series)
        - seq_len
        - pred_len
        + 1
    )

    for start in range(
        0,
        max_start,
        step,
    ):

        context = series[
            start:
            start + seq_len
        ]

        target = series[
            start + seq_len:
            start + seq_len + pred_len
        ]

        context_windows.append(
            context
        )

        gt_windows.append(
            target[:, np.newaxis]
        )

    if not context_windows:

        raise ValueError(
            "No windows could be created. "
            f"Series length={len(series)}, "
            f"seq_len={seq_len}, "
            f"pred_len={pred_len}."
        )

    return (
        np.asarray(
            context_windows,
            dtype=np.float32,
        ),
        np.asarray(
            gt_windows,
            dtype=np.float32,
        ),
    )


# ============================================================
# PERSISTENCE / NAIVE FORECAST
# ============================================================

def persistence_forecast(
    context_windows,
    pred_len,
):
    """
    Last-value persistence forecast.

    Input:
        [n_windows, seq_len]

    Output:
        [n_windows, pred_len, 1]
    """

    context_windows = np.asarray(
        context_windows,
        dtype=float,
    )

    last_value = (
        context_windows[:, -1:]
    )

    predictions = np.repeat(
        last_value,
        pred_len,
        axis=1,
    )

    return predictions[:, :, np.newaxis]


# ============================================================
# HR THRESHOLD CALIBRATION
# ============================================================

def calibrate_hr_thresholds(
    training_targets,
    training_naive_predictions,
    quantiles=(0.90, 0.95, 0.99),
):
    """
    Calibrate horizon-wise hallucination thresholds
    using TRAINING data only.

    The thresholds are based on absolute errors from
    a model-independent persistence forecast.

    Returns
    -------
    dict
        {
            0.90: [pred_len, 1],
            0.95: [pred_len, 1],
            0.99: [pred_len, 1]
        }
    """

    training_targets = np.asarray(
        training_targets,
        dtype=float,
    )

    training_naive_predictions = np.asarray(
        training_naive_predictions,
        dtype=float,
    )

    if (
        training_targets.shape
        != training_naive_predictions.shape
    ):
        raise ValueError(
            "Training targets and naive predictions "
            "must have identical shapes."
        )

    errors = np.abs(
        training_targets
        - training_naive_predictions
    )

    thresholds = {}

    for q in quantiles:

        thresholds[q] = np.quantile(
            errors,
            q,
            axis=0,
        )

    return thresholds


# ============================================================
# TRAINING RANGE
# ============================================================

def calculate_training_range(
    training_series_scaled,
):
    """
    Calculate the minimum and maximum training values
    in the SAME scale used for evaluation.
    """

    training_series_scaled = np.asarray(
        training_series_scaled,
        dtype=float,
    )

    training_minimum = np.min(
        training_series_scaled
    )

    training_maximum = np.max(
        training_series_scaled
    )

    return (
        np.array(
            [[[training_minimum]]],
            dtype=np.float32,
        ),
        np.array(
            [[[training_maximum]]],
            dtype=np.float32,
        ),
    )


