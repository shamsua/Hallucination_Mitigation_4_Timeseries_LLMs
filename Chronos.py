# 10. MASTER FORECAST EVALUATION
# ============================================================

def evaluate_forecasts(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    hr_thresholds: dict[float, np.ndarray],
    training_minimum: np.ndarray,
    training_maximum: np.ndarray,
    gaussian_calibration: GaussianCalibration | None = None,
    mape_epsilon: float = 1e-6,
    dtw_max_samples: int = 256,
    dtw_seed: int = 0,
) -> dict[str, float]:
    """
    Evaluate deterministic forecasts using the complete metric set.

    Expected shape for y_true and y_pred:
        [samples, horizon, channels]

    Metrics:
        MSE
        MAE
        RMSE
        MAPE
        TCE
        normalized DTW
        range violation rate
        HR at q=0.90
        HR at q=0.95
        HR at q=0.99
        Gaussian NLL
        Gaussian perplexity
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            f"Shape mismatch: y_true={y_true.shape}, "
            f"y_pred={y_pred.shape}"
        )

    results = {

        # Conventional forecasting metrics
        "mse": mse(
            y_true,
            y_pred,
        ),

        "mae": mae(
            y_true,
            y_pred,
        ),

        "rmse": rmse(
            y_true,
            y_pred,
        ),

        "mape": mape(
            y_true,
            y_pred,
            mape_epsilon,
        ),

        # Temporal behaviour
        "tce": temporal_consistency_error(
            y_true,
            y_pred,
        ),

        "dtw": normalized_dtw(
            y_true,
            y_pred,
            max_samples=dtw_max_samples,
            seed=dtw_seed,
        ),

        # Numerical plausibility
        "range_violation_rate": range_violation_rate(
            y_pred,
            training_minimum,
            training_maximum,
        ),
    }

    # Hallucination rates
    for quantile, thresholds in hr_thresholds.items():

        results[
            f"hr_q{int(round(quantile * 100)):02d}"
        ] = hallucination_rate(
            y_true,
            y_pred,
            thresholds,
        )

    # Probabilistic calibration metrics
    if gaussian_calibration is not None:

        results["gaussian_nll"] = gaussian_nll(
            y_true,
            y_pred,
            gaussian_calibration,
        )

        results["gaussian_perplexity"] = gaussian_perplexity(
            y_true,
            y_pred,
            gaussian_calibration,
        )

    return results


