def run_chronos(
    context_windows,
    pred_len,
    num_samples=100,
    batch_size=32,
):
    """
    Generate probabilistic forecasts using Chronos.

    Parameters
    ----------
    context_windows:
        Historical contexts.

        Shape:
            [n_windows, seq_len]

    pred_len:
        Forecast horizon.

    num_samples:
        Number of probabilistic forecast samples
        generated for each window.

    batch_size:
        Number of windows processed per batch.

    Returns
    -------
    forecast_samples:
        NumPy array with shape:

            [n_windows, num_samples, pred_len]

    Notes
    -----
    The returned samples should be retained for probabilistic
    evaluation such as CRPS and prediction-interval coverage.

    For deterministic metrics, use the median across samples.
    """

    context_windows = np.asarray(
        context_windows,
        dtype=np.float32,
    )

    if context_windows.ndim != 2:

        raise ValueError(
            "Expected context_windows with shape "
            "[n_windows, seq_len]. "
            f"Received: {context_windows.shape}"
        )

    if pred_len <= 0:

        raise ValueError(
            "pred_len must be greater than zero."
        )

    if num_samples <= 0:

        raise ValueError(
            "num_samples must be greater than zero."
        )

    all_forecasts = []

    # --------------------------------------------------------
    # Batch inference
    # --------------------------------------------------------

    for start in tqdm(
        range(
            0,
            len(context_windows),
            batch_size,
        ),
        desc="Chronos forecasting",
    ):

        batch = context_windows[
            start:
            start + batch_size
        ]

        # Chronos accepts a list of 1-D tensors.
        tensors = [
            torch.as_tensor(
                window,
                dtype=torch.float32,
            )
            for window in batch
        ]

        # ----------------------------------------------------
        # Inference
        # ----------------------------------------------------

        with torch.inference_mode():

            forecast = pipeline.predict(
                tensors,
                prediction_length=pred_len,
                num_samples=num_samples,
            )

        # ----------------------------------------------------
        # Convert each forecast to CPU NumPy
        # ----------------------------------------------------

        batch_arr = np.stack(
            [
                sample.detach()
                .float()
                .cpu()
                .numpy()
                for sample in forecast
            ],
            axis=0,
        )

        # Expected:
        #
        # [batch_size, num_samples, pred_len]
        #
        if batch_arr.ndim != 3:

            raise RuntimeError(
                "Unexpected Chronos output shape: "
                f"{batch_arr.shape}"
            )

        if batch_arr.shape[2] != pred_len:

            raise RuntimeError(
                "Chronos returned an unexpected "
                f"forecast horizon: {batch_arr.shape}"
            )

        all_forecasts.append(
            batch_arr
        )

    # --------------------------------------------------------
    # Combine batches
    # --------------------------------------------------------

    if not all_forecasts:

        raise RuntimeError(
            "Chronos produced no forecasts."
        )

    forecast_samples = np.concatenate(
        all_forecasts,
        axis=0,
    )

    print(
        "\nChronos forecast samples:"
    )

    print(
        f"  Shape       : "
        f"{forecast_samples.shape}"
    )

    print(
        f"  Windows     : "
        f"{forecast_samples.shape[0]}"
    )

    print(
        f"  MC samples  : "
        f"{forecast_samples.shape[1]}"
    )

    print(
        f"  Horizon     : "
        f"{forecast_samples.shape[2]}"
    )

    return forecast_samples


# ============================================================
# 5. CONVERT PROBABILISTIC FORECAST TO DETERMINISTIC MEDIAN
# ============================================================

def chronos_median_forecast(
    forecast_samples,
):
    """
    Convert probabilistic Chronos forecasts into the
    median forecast used for deterministic metrics.

    Input:
        [n_windows, num_samples, pred_len]

    Output:
        [n_windows, pred_len, 1]
    """

    forecast_samples = np.asarray(
        forecast_samples,
        dtype=np.float32,
    )

    if forecast_samples.ndim != 3:

        raise ValueError(
            "Expected forecast_samples with shape "
            "[n_windows, num_samples, pred_len]. "
            f"Received: {forecast_samples.shape}"
        )

    median_forecast = np.median(
        forecast_samples,
        axis=1,
    )

    return (
        median_forecast[:, :, np.newaxis]
        .astype(np.float32)
    )


# ============================================================
# 6. OPTIONAL: PREDICTION INTERVALS
# ============================================================

def chronos_prediction_intervals(
    forecast_samples,
    lower=0.10,
    upper=0.90,
):
    """
    Calculate empirical prediction intervals.

    Input:
        [n_windows, num_samples, pred_len]

    Returns:
        lower_bound:
            [n_windows, pred_len, 1]

        median:
            [n_windows, pred_len, 1]

        upper_bound:
            [n_windows, pred_len, 1]
    """

    forecast_samples = np.asarray(
        forecast_samples,
        dtype=np.float32,
    )

    lower_bound = np.quantile(
        forecast_samples,
        lower,
        axis=1,
    )

    median = np.quantile(
        forecast_samples,
        0.50,
        axis=1,
    )

    upper_bound = np.quantile(
        forecast_samples,
        upper,
        axis=1,
    )

    return (
        lower_bound[:, :, np.newaxis],
        median[:, :, np.newaxis],
        upper_bound[:, :, np.newaxis],
    )


