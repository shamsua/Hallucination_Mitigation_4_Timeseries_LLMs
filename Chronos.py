# 9. TRAIN / VALIDATION / TEST SPLIT
# ============================================================

def chronological_split(
    data: np.ndarray,
    train_ratio: float = 0.70,
    val_ratio: float = 0.10,
):
    """
    Chronological split.

    IMPORTANT:
    No shuffling is performed.

    Returns:
        train
        validation
        test
    """

    n = len(data)

    train_end = int(
        n * train_ratio
    )

    val_end = train_end + int(
        n * val_ratio
    )

    train = data[:train_end]

    validation = data[
        train_end:val_end
    ]

    test = data[
        val_end:
    ]

    return (
        train,
        validation,
        test,
    )


# ============================================================
# 10. CREATE FORECAST WINDOWS
# ============================================================

def create_forecast_windows(
    data: np.ndarray,
    input_len: int,
    pred_len: int,
):
    """
    Create supervised forecasting windows.

    Input:
        [input_len, channels]

    Target:
        [pred_len, channels]
    """

    data = np.asarray(
        data,
        dtype=np.float32,
    )

    X = []
    y = []

    max_start = (
        len(data)
        - input_len
        - pred_len
        + 1
    )

    for start in range(
        max_start
    ):

        end_input = (
            start + input_len
        )

        end_target = (
            end_input + pred_len
        )

        X.append(
            data[
                start:end_input
            ]
        )

        y.append(
            data[
                end_input:end_target
            ]
        )

    if not X:

        raise ValueError(
            "No forecasting windows could "
            "be created. Check input_len, "
            "pred_len, and dataset size."
        )

    return (
        np.asarray(X),
        np.asarray(y),
    )


# ============================================================
# 11. NAIVE FORECAST
# ============================================================

def persistence_forecast(
    X: np.ndarray,
    pred_len: int,
) -> np.ndarray:
    """
    Last-value persistence forecast.

    Each future time step receives the
    last observed input value.

    X:
        [samples, input_len, channels]

    Returns:
        [samples, pred_len, channels]
    """

    last_value = X[:, -1:, :]

    return np.repeat(
        last_value,
        pred_len,
        axis=1,
    )


# ============================================================
# 12. CALIBRATE HR THRESHOLDS
# ============================================================

def prepare_hr_calibration(
    train_X: np.ndarray,
    train_y: np.ndarray,
    quantiles=(
        0.90,
        0.95,
        0.99,
    ),
):
    """
    Prepare hallucination-rate thresholds
    from training data only.

    Uses persistence forecasting as the
    model-independent reference.
    """

    naive_predictions = persistence_forecast(
        train_X,
        pred_len=train_y.shape[1],
    )

    errors = np.abs(
        train_y -
        naive_predictions
    )

    thresholds = {
        q: np.quantile(
            errors,
            q,
            axis=0,
        )
        for q in quantiles
    }

    return (
        thresholds,
        naive_predictions,
    )


# ============================================================
# 13. TRAINING RANGE
# ============================================================

def prepare_training_range(
    train_y: np.ndarray,
):
    """
    Calculate minimum and maximum values
    from training targets only.
    """

    training_minimum = np.min(
        train_y,
        axis=(0, 1),
        keepdims=True,
    )

    training_maximum = np.max(
        train_y,
        axis=(0, 1),
        keepdims=True,
    )

    return (
        training_minimum,
        training_maximum,
    )


