import numpy as np


# ============================================================
# 1. BASIC FORECASTING METRICS
# ============================================================

def mse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """Mean Squared Error."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    return float(np.mean((y_true - y_pred) ** 2))


def mae(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """Mean Absolute Error."""
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    return float(np.mean(np.abs(y_true - y_pred)))


def rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """Root Mean Squared Error."""
    return float(np.sqrt(mse(y_true, y_pred)))


def mape(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    epsilon: float = 1e-6,
) -> float:
    """
    Mean Absolute Percentage Error.

    Returns MAPE in percentage units.
    """
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    denominator = np.maximum(np.abs(y_true), epsilon)

    return float(
        100.0
        * np.mean(np.abs(y_true - y_pred) / denominator)
    )


# ============================================================
# 2. TEMPORAL CONSISTENCY ERROR
# ============================================================

def temporal_consistency_error(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> float:
    """
    Temporal Consistency Error (TCE).

    Measures the difference between consecutive temporal
    transitions in the ground truth and prediction.

    Expected shape:
        [samples, horizon, channels]
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            f"Shape mismatch: y_true={y_true.shape}, "
            f"y_pred={y_pred.shape}"
        )

    if y_true.ndim != 3:
        raise ValueError(
            "Expected arrays with shape "
            "[samples, horizon, channels]."
        )

    if y_true.shape[1] < 2:
        raise ValueError(
            "Forecast horizon must contain at least "
            "2 time steps to calculate TCE."
        )

    true_delta = np.diff(y_true, axis=1)
    pred_delta = np.diff(y_pred, axis=1)

    return float(
        np.mean(np.abs(true_delta - pred_delta))
    )


# ============================================================
# 3. NORMALIZED DTW
# ============================================================

def _dtw_1d(
    a: np.ndarray,
    b: np.ndarray,
) -> float:
    """
    Calculate normalized DTW distance between two 1-D sequences.

    The distance is normalized by n + m to improve comparability
    across different forecast horizons.
    """

    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)

    n = len(a)
    m = len(b)

    previous = np.full(m + 1, np.inf)
    previous[0] = 0.0

    for i in range(1, n + 1):

        current = np.full(m + 1, np.inf)

        for j in range(1, m + 1):

            cost = abs(a[i - 1] - b[j - 1])

            current[j] = cost + min(
                current[j - 1],      # insertion
                previous[j],         # deletion
                previous[j - 1],     # match
            )

        previous = current

    return float(
        previous[m] / max(n + m, 1)
    )


def normalized_dtw(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    max_samples: int = 256,
    seed: int = 0,
) -> float:
    """
    Mean normalized DTW distance.

    To control computational cost, at most max_samples forecast
    windows are evaluated.

    A fixed seed makes sampling reproducible.
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            f"Shape mismatch: y_true={y_true.shape}, "
            f"y_pred={y_pred.shape}"
        )

    if y_true.ndim != 3:
        raise ValueError(
            "Expected arrays with shape "
            "[samples, horizon, channels]."
        )

    rng = np.random.default_rng(seed)

    indices = np.arange(len(y_true))

    if len(indices) > max_samples:
        indices = np.sort(
            rng.choice(
                indices,
                size=max_samples,
                replace=False,
            )
        )

    distances = [
        _dtw_1d(
            y_true[i, :, channel],
            y_pred[i, :, channel],
        )
        for i in indices
        for channel in range(y_true.shape[-1])
    ]

    if not distances:
        return 0.0

    return float(np.mean(distances))


# ============================================================
# 4. HALLUCINATION-RATE THRESHOLD CALIBRATION
# ============================================================

def calibrate_hr_thresholds(
    training_targets: np.ndarray,
    training_naive_predictions: np.ndarray,
    quantiles: tuple[float, ...] = (
        0.90,
        0.95,
        0.99,
    ),
) -> dict[float, np.ndarray]:
    """
    Calibrate horizon-wise hallucination thresholds using
    TRAINING data only.

    The thresholds represent the empirical distribution of
    absolute prediction errors from a naive/reference predictor.

    Parameters
    ----------
    training_targets:
        Ground-truth training windows.

    training_naive_predictions:
        Predictions generated by a naive/reference forecasting
        strategy using the training data.

    quantiles:
        Error quantiles used to define hallucination thresholds.

    Returns
    -------
    dict
        Mapping from quantile to horizon-wise thresholds.
    """

    training_targets = np.asarray(training_targets)
    training_naive_predictions = np.asarray(
        training_naive_predictions
    )

    if training_targets.shape != training_naive_predictions.shape:
        raise ValueError(
            "Training target and naive prediction shapes "
            "must match."
        )

    errors = np.abs(
        training_targets -
        training_naive_predictions
    )

    return {
        q: np.quantile(
            errors,
            q,
            axis=0,
        )
        for q in quantiles
    }


# ============================================================
# 5. HALLUCINATION RATE
# ============================================================

def hallucination_rate(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    thresholds: np.ndarray,
) -> float:
    """
    Hallucination Rate (HR).

    A forecast value is considered a hallucination when its
    absolute error exceeds the corresponding calibrated
    horizon-wise threshold.

    HR = number of threshold violations / total forecast values.
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    thresholds = np.asarray(thresholds)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes."
        )

    errors = np.abs(
        y_true - y_pred
    )

    violations = errors > thresholds

    return float(
        np.mean(violations)
    )


# ============================================================
# 6. RANGE VIOLATION RATE
# ============================================================

def range_violation_rate(
    y_pred: np.ndarray,
    training_minimum: np.ndarray,
    training_maximum: np.ndarray,
) -> float:
    """
    Range Violation Rate.

    Measures the proportion of predicted values outside the
    observed training-data range.

    This provides an additional physical/numerical plausibility
    check for hallucinated forecasts.
    """

    y_pred = np.asarray(y_pred)
    training_minimum = np.asarray(training_minimum)
    training_maximum = np.asarray(training_maximum)

    violations = (
        (y_pred < training_minimum)
        |
        (y_pred > training_maximum)
    )

    return float(
        np.mean(violations)
    )


