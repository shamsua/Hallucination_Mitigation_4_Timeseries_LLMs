# 7. GAUSSIAN CALIBRATION
# ============================================================

@dataclass
class GaussianCalibration:
    """
    Gaussian residual calibration parameters.
    """

    bias: np.ndarray
    sigma: np.ndarray


def fit_gaussian_calibration(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> GaussianCalibration:
    """
    Fit Gaussian residual calibration.

    Bias:
        Mean residual.

    Sigma:
        Standard deviation of residuals.
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    if y_true.shape != y_pred.shape:
        raise ValueError(
            "y_true and y_pred must have identical shapes."
        )

    residual = y_true - y_pred

    return GaussianCalibration(
        bias=np.mean(
            residual,
            axis=0,
        ),
        sigma=np.maximum(
            np.std(
                residual,
                axis=0,
            ),
            1e-6,
        ),
    )


# ============================================================
# 8. GAUSSIAN NEGATIVE LOG-LIKELIHOOD
# ============================================================

def gaussian_nll(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    calibration: GaussianCalibration,
) -> float:
    """
    Mean Gaussian Negative Log-Likelihood (NLL).

    This evaluates probabilistic consistency of the forecast
    under the calibrated Gaussian residual model.
    """

    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)

    residual = (
        y_true
        - y_pred
        - calibration.bias
    )

    variance = calibration.sigma ** 2

    value = 0.5 * (
        np.log(
            2.0 * np.pi * variance
        )
        +
        residual ** 2 / variance
    )

    return float(
        np.mean(value)
    )


# ============================================================
# 9. GAUSSIAN PERPLEXITY
# ============================================================

def gaussian_perplexity(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    calibration: GaussianCalibration,
) -> float:
    """
    Continuous Gaussian likelihood perplexity.

    PP = exp(mean Gaussian NLL)

    IMPORTANT:
    This is NOT language-model token perplexity.
    It is a continuous forecasting likelihood measure.

    Comparisons should use the same:
        - dataset
        - units
        - data split
        - target scaling
        - calibration procedure
    """

    mean_nll = gaussian_nll(
        y_true,
        y_pred,
        calibration,
    )

    return float(
        np.exp(
            np.clip(
                mean_nll,
                -700.0,
                700.0,
            )
        )
    )


